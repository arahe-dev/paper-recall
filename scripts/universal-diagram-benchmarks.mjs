function styleSuiteInputs(baseByType) {
  const mapping = {
    readable_default: "deadlock_concept_map",
    readable_compact: "dense_graph",
    readable_spacious: "team_hierarchy",
    readable_radial: "esp32_imu_hub",
    readable_flowchart: "password_reset_flowchart",
    readable_block_diagram: "data_pipeline_block_diagram",
    readable_system_architecture: "database_replication_architecture",
    readable_timeline: "project_timeline",
    readable_matrix: "storage_comparison_matrix",
    readable_cycle: "krebs_cycle",
  };
  return styleNames.map((styleName) => {
    const base = baseByType.get(mapping[styleName]);
    const cloned = JSON.parse(JSON.stringify(base.spec));
    cloned.title = `${styleName} ${cloned.title}`;
    cloned.layout = { ...(cloned.layout || {}), style: styleName };
    return {
      scenario: `style_${styleName}`,
      category: "style_variant",
      spec: cloned,
    };
  });
}

function normalizeText(value) {
  return String(value || "")
    .toLowerCase()
    .replace(/\s+/g, " ")
    .trim();
}

function pngDimensions(path) {
  const bytes = readFileSync(path);
  if (
    bytes.length < 24 ||
    bytes[0] !== 0x89 ||
    bytes[1] !== 0x50 ||
    bytes[2] !== 0x4e ||
    bytes[3] !== 0x47
  ) {
    return null;
  }
  return {
    width: bytes.readUInt32BE(16),
    height: bytes.readUInt32BE(20),
  };
}

function isIgnored(el) {
  return el?.customData?.recallIgnoreInTextGraph === true;
}

function activeElements(scene) {
  return (scene.elements || []).filter((el) => !el.isDeleted);
}

function nodeShapes(scene) {
  return activeElements(scene).filter(
    (el) =>
      (el.type === "rectangle" || el.type === "ellipse" || el.type === "diamond") &&
      !isIgnored(el) &&
      el.customData?.recallEntityType === "node"
  );
}

function semanticTexts(scene) {
  const arrowIds = new Set(activeElements(scene).filter((el) => el.type === "arrow").map((el) => el.id));
  const ignoredIds = new Set(activeElements(scene).filter(isIgnored).map((el) => el.id));
  return activeElements(scene).filter(
    (el) =>
      el.type === "text" &&
      !isIgnored(el) &&
      !(el.containerId && ignoredIds.has(el.containerId)) &&
      !(el.containerId && arrowIds.has(el.containerId))
  );
}

function rectsOverlap(a, b, gap = 2) {
  return (
    a.x < b.x + b.width + gap &&
    a.x + a.width + gap > b.x &&
    a.y < b.y + b.height + gap &&
    a.y + a.height + gap > b.y
  );
}

function pointInsideRect(px, py, rect, inset = 0) {
  return (
    px > rect.x + inset &&
    px < rect.x + rect.width - inset &&
    py > rect.y + inset &&
    py < rect.y + rect.height - inset
  );
}

function arrowAbsPoints(arrow) {
  const points = Array.isArray(arrow.points) ? arrow.points : [[0, 0], [arrow.width || 0, arrow.height || 0]];
  return points.map((point) => ({ x: (arrow.x || 0) + point[0], y: (arrow.y || 0) + point[1] }));
}

function polylineLength(points) {
  let total = 0;
  for (let i = 1; i < points.length; i++) {
    total += Math.hypot(points[i].x - points[i - 1].x, points[i].y - points[i - 1].y);
  }
  return total;
}

function countPolylineRectHits(points, rects, excludedNodeIds = new Set()) {
  const hits = new Set();
  for (let i = 1; i < points.length; i++) {
    const a = points[i - 1];
    const b = points[i];
    const steps = Math.max(8, Math.ceil(Math.hypot(b.x - a.x, b.y - a.y) / 18));
    for (let s = 1; s < steps; s++) {
      const t = s / steps;
      const px = a.x + (b.x - a.x) * t;
      const py = a.y + (b.y - a.y) * t;
      for (const rect of rects) {
        const nodeId = rect.customData?.recallNodeId;
        if (nodeId && excludedNodeIds.has(nodeId)) continue;
        if (pointInsideRect(px, py, rect, 8)) {
          hits.add(rect.id);
        }
      }
    }
  }
  return hits.size;
}

function scoreReadability(scene, pngPath, options = {}) {
  const defects = [];
  const active = activeElements(scene);
  const shapes = nodeShapes(scene);
  const arrows = active.filter((el) => el.type === "arrow" && !isIgnored(el));
  const texts = semanticTexts(scene);

  if (shapes.length === 0) defects.push("no semantic node shapes rendered");
  if (pngPath) {
    const dimensions = pngDimensions(pngPath);
    if (!dimensions || dimensions.width < 160 || dimensions.height < 60) {
      defects.push("PNG export missing or too small");
    }
  }

  const overlapPairs = [];
  for (let i = 0; i < shapes.length; i++) {
    for (let j = i + 1; j < shapes.length; j++) {
      if (rectsOverlap(shapes[i], shapes[j])) overlapPairs.push(`${shapes[i].id}/${shapes[j].id}`);
    }
  }
  if (overlapPairs.length > 0) defects.push(`node overlaps: ${overlapPairs.slice(0, 5).join(", ")}`);

  const degenerateArrows = [];
  const unboundArrows = [];
  const missingArrowheads = [];
  const arrowNodeHits = [];
  const arrowTextHits = [];
  for (const arrow of arrows) {
    const points = arrowAbsPoints(arrow);
    if (polylineLength(points) < 12) degenerateArrows.push(arrow.id);
    if (!arrow.endArrowhead) missingArrowheads.push(arrow.id);
    if (!arrow.startBinding || !arrow.endBinding) unboundArrows.push(arrow.id);
    const excluded = new Set([
      arrow.customData?.recallFromNodeId,
      arrow.customData?.recallToNodeId,
    ].filter(Boolean));
    const nodeHits = countPolylineRectHits(points, shapes, excluded);
    if (nodeHits > 0) arrowNodeHits.push(`${arrow.id}:${nodeHits}`);
    const endpointElementIds = new Set([
      arrow.startBinding?.elementId,
      arrow.endBinding?.elementId,
    ].filter(Boolean));
    const textHits = countPolylineRectHits(
      points,
      texts.filter((text) => !(text.containerId && endpointElementIds.has(text.containerId))),
      new Set()
    );
    if (textHits > 0) arrowTextHits.push(`${arrow.id}:${textHits}`);
  }
  if (degenerateArrows.length > 0) defects.push(`degenerate arrows: ${degenerateArrows.join(", ")}`);
  if (!options.allowLooseEdges && unboundArrows.length > 0) defects.push(`unbound arrows: ${unboundArrows.join(", ")}`);
  if (missingArrowheads.length > 0) defects.push(`missing arrowheads: ${missingArrowheads.join(", ")}`);
  if (arrowNodeHits.length > 0) defects.push(`arrows pass through nodes: ${arrowNodeHits.slice(0, 5).join(", ")}`);
  if (arrowTextHits.length > 0) defects.push(`arrows pass through text: ${arrowTextHits.slice(0, 5).join(", ")}`);

  let score = 1;
  score -= Math.min(0.55, overlapPairs.length * 0.18);
  score -= Math.min(0.5, degenerateArrows.length * 0.18);
  if (!options.allowLooseEdges) score -= Math.min(0.3, unboundArrows.length * 0.05);
  score -= Math.min(0.3, missingArrowheads.length * 0.05);
  score -= Math.min(0.45, arrowNodeHits.length * 0.05);
  score -= Math.min(0.35, arrowTextHits.length * 0.05);
  score = Math.max(0, Math.min(1, score));

  return {
    score: Number(score.toFixed(2)),
    pass: score >= READABILITY_THRESHOLD,
    defects,
    metrics: {
      active_element_count: active.length,
      semantic_node_count: shapes.length,
      semantic_text_count: texts.length,
      arrow_count: arrows.length,
      overlap_pair_count: overlapPairs.length,
      degenerate_arrow_count: degenerateArrows.length,
      unbound_arrow_count: unboundArrows.length,
      missing_arrowhead_count: missingArrowheads.length,
      arrow_node_hit_count: arrowNodeHits.length,
      arrow_text_hit_count: arrowTextHits.length,
      png_dimensions: pngPath ? pngDimensions(pngPath) : null,
    },
  };
}

function setEqual(expected, actual) {
  const missing = [...expected].filter((id) => !actual.has(id));
  const extra = [...actual].filter((id) => !expected.has(id));
  return { missing, extra };
}

function edgeKey(edge) {
  return `${edge.from}->${edge.to}${edge.label ? `:${normalizeText(edge.label)}` : ""}`;
}

function actualEdgeKey(edge) {
  return `${edge.from_node_id}->${edge.to_node_id}${edge.label ? `:${normalizeText(edge.label)}` : ""}`;
}

function scoreParseFidelity(expectedGraph, textGraph, options = {}) {
  const defects = [];
  const expectedNodeIds = new Set((expectedGraph.nodes || []).map((node) => node.id));
  const actualNodeIds = new Set((textGraph.nodes || []).map((node) => node.id));
  const nodeDiff = setEqual(expectedNodeIds, actualNodeIds);
  if (nodeDiff.missing.length > 0) defects.push(`missing nodes: ${nodeDiff.missing.join(", ")}`);
  if (nodeDiff.extra.length > 0) defects.push(`extra nodes: ${nodeDiff.extra.join(", ")}`);

  const expectedLabels = new Map((expectedGraph.nodes || []).map((node) => [node.id, normalizeText(node.label)]));
  const actualLabels = new Map((textGraph.nodes || []).map((node) => [node.id, normalizeText(node.label)]));
  const badLabels = [];
  for (const [nodeId, label] of expectedLabels) {
    if (actualLabels.has(nodeId) && actualLabels.get(nodeId) !== label) badLabels.push(nodeId);
  }
  if (badLabels.length > 0) defects.push(`node label mismatches: ${badLabels.join(", ")}`);

  const expectedEdgeIds = new Set((expectedGraph.edges || []).map((edge) => edge.id));
  const actualEdgeIds = new Set((textGraph.edges || []).map((edge) => edge.id));
  const edgeDiff = setEqual(expectedEdgeIds, actualEdgeIds);
  if (edgeDiff.missing.length > 0) defects.push(`missing edges: ${edgeDiff.missing.join(", ")}`);
  if (edgeDiff.extra.length > 0) defects.push(`extra edges: ${edgeDiff.extra.join(", ")}`);

  const expectedEdgeKeys = new Set((expectedGraph.edges || []).map(edgeKey));
  const actualEdgeKeys = new Set((textGraph.edges || []).map(actualEdgeKey));
  const keyDiff = setEqual(expectedEdgeKeys, actualEdgeKeys);
  if (keyDiff.missing.length > 0) defects.push(`missing edge relations: ${keyDiff.missing.slice(0, 5).join(", ")}`);
  if (keyDiff.extra.length > 0) defects.push(`extra edge relations: ${keyDiff.extra.slice(0, 5).join(", ")}`);

  const expectedGroupIds = new Set((expectedGraph.groups || []).map((group) => group.id));
  const actualGroupIds = new Set((textGraph.groups || []).map((group) => group.id));
  const groupDiff = setEqual(expectedGroupIds, actualGroupIds);
  if (groupDiff.missing.length > 0) defects.push(`missing groups: ${groupDiff.missing.join(", ")}`);
  if (groupDiff.extra.length > 0) defects.push(`extra groups: ${groupDiff.extra.join(", ")}`);

  const expectedAnnotationIds = new Set((expectedGraph.annotations || []).map((annotation) => annotation.id));
  const actualAnnotationIds = new Set((textGraph.annotations || []).map((annotation) => annotation.id));
  const annotationDiff = setEqual(expectedAnnotationIds, actualAnnotationIds);
  if (annotationDiff.missing.length > 0) defects.push(`missing annotations: ${annotationDiff.missing.join(", ")}`);
  if (annotationDiff.extra.length > 0) defects.push(`extra annotations: ${annotationDiff.extra.join(", ")}`);

  const unresolved = textGraph.unresolved_arrows || [];
  const ungrouped = textGraph.ungrouped_text || [];
  const loose = (textGraph.edges || []).filter((edge) => edge.status === "loose_inferred_relation");
  if (unresolved.length > 0) defects.push(`unresolved arrows: ${unresolved.map((arrow) => arrow.id).join(", ")}`);
  if (ungrouped.length > 0) defects.push(`ungrouped text: ${ungrouped.map((text) => text.text).join(", ")}`);
  if (!options.allowLooseEdges && loose.length > 0) defects.push(`loose inferred edges: ${loose.map((edge) => edge.id).join(", ")}`);

  let score = 1;
  score -= Math.min(0.45, (nodeDiff.missing.length / Math.max(1, expectedNodeIds.size)) * 0.45);
  score -= Math.min(0.2, (nodeDiff.extra.length / Math.max(1, expectedNodeIds.size)) * 0.2);
  score -= Math.min(0.2, (badLabels.length / Math.max(1, expectedNodeIds.size)) * 0.2);
  score -= Math.min(0.45, (edgeDiff.missing.length / Math.max(1, expectedEdgeIds.size || 1)) * 0.45);
  score -= Math.min(0.2, (edgeDiff.extra.length / Math.max(1, expectedEdgeIds.size || 1)) * 0.2);
  score -= Math.min(0.2, (keyDiff.missing.length / Math.max(1, expectedEdgeKeys.size || 1)) * 0.2);
  score -= Math.min(0.12, (groupDiff.missing.length / Math.max(1, expectedGroupIds.size || 1)) * 0.12);
  score -= Math.min(0.12, (annotationDiff.missing.length / Math.max(1, expectedAnnotationIds.size || 1)) * 0.12);
  score -= Math.min(0.3, unresolved.length * 0.1);
  score -= Math.min(0.2, ungrouped.length * 0.05);
  if (!options.allowLooseEdges) score -= Math.min(0.2, loose.length * 0.04);
  score = Math.max(0, Math.min(1, score));

  return {
    score: Number(score.toFixed(2)),
    pass: score >= PARSE_THRESHOLD,
    defects,
    metrics: {
      expected_node_count: expectedNodeIds.size,
      actual_node_count: actualNodeIds.size,
      expected_edge_count: expectedEdgeIds.size,
      actual_edge_count: actualEdgeIds.size,
      expected_group_count: expectedGroupIds.size,
      actual_group_count: actualGroupIds.size,
      expected_annotation_count: expectedAnnotationIds.size,
      actual_annotation_count: actualAnnotationIds.size,
      unresolved_arrow_count: unresolved.length,
      ungrouped_text_count: ungrouped.length,
      loose_edge_count: loose.length,
    },
  };
}

